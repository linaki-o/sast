"""Unit tests for the sample project.

The suite exercises the C functions of ``src/utils.c`` and ``src/features.c``
through the CodeShield interpreter engine, so the tests run on any machine
without a C toolchain.

Run them with::

    sast test examples/sample_project
"""

from sast.testing import TestCase, TestSuite

SUITE = TestSuite(
    name="utils",
    description="Unit tests for the utility functions of the sample project",
    source_files=[
        "src/utils.c",
        "src/features.c",
    ],
    tests=[
        TestCase(
            id="TC-COMPUTE-001",
            name="compute adds two positive numbers",
            target="compute",
            description="compute(2, 3) returns 5 and writes 5 to the output pointer.",
            params=[2, 3, "&out"],
            setup=["int out;"],
            expected=5,
            assert_expr="out == 5",
            requirement_ids=["REQ-001"],
            tags=["compute", "arithmetic"],
        ),
        TestCase(
            id="TC-COMPUTE-002",
            name="compute rejects a null output pointer",
            target="compute",
            description="A null output pointer makes compute return -1.",
            params=[1, 1, 0],
            expected=-1,
            requirement_ids=["REQ-001"],
            tags=["compute", "robustness"],
        ),
        TestCase(
            id="TC-COMPUTE-003",
            name="compute treats a negative operand as zero",
            target="compute",
            description="A negative first operand produces 0.",
            params=[-5, 4, "&out"],
            setup=["int out;"],
            expected=0,
            assert_expr="out == 0",
            requirement_ids=["REQ-001"],
            tags=["compute"],
        ),
        TestCase(
            id="TC-COPY-001",
            name="copy_name copies the source string",
            target="copy_name",
            description="copy_name copies 'abc' into the destination buffer.",
            params=["&dst", "abc"],
            setup=["char dst[64];"],
            assert_expr="dst[0] == 'a' && dst[1] == 'b' && dst[2] == 'c'",
            requirement_ids=["REQ-002"],
            tags=["copy_name", "string"],
        ),
        TestCase(
            id="TC-DIVIDE-001",
            name="divide returns the quotient",
            target="divide",
            description="divide(6, 3) returns 2.",
            params=[6, 3],
            expected=2,
            requirement_ids=["REQ-003"],
            tags=["divide"],
        ),
        TestCase(
            id="TC-DIVIDE-002",
            name="divide guards against a zero divisor",
            target="divide",
            description="divide(6, 0) returns 0 instead of trapping.",
            params=[6, 0],
            expected=0,
            requirement_ids=["REQ-003"],
            tags=["divide", "robustness"],
        ),
        TestCase(
            id="TC-GREET-001",
            name="make_greeting builds a personalised greeting",
            target="make_greeting",
            description="make_greeting('Ann') greets Ann.",
            params=["Ann"],
            expected="Hello, Ann!",
            requirement_ids=["REQ-004"],
            tags=["make_greeting"],
        ),
        TestCase(
            id="TC-CLASSIFY-001",
            name="classify maps the running state",
            target="classify",
            description="The running state maps to 1.",
            params=[1],
            expected=1,
            tags=["classify"],
        ),
        TestCase(
            id="TC-CLASSIFY-002",
            name="classify maps the idle state",
            target="classify",
            description="The idle state maps to 0.",
            params=[0],
            expected=0,
            tags=["classify"],
        ),
        TestCase(
            id="TC-RISKY-001",
            name="risky_division reports an error for a zero divisor",
            target="risky_division",
            description="risky_division(10, 0) returns -1.",
            params=[10, 0],
            expected=-1,
            tags=["risky_division", "robustness"],
        ),
        TestCase(
            id="TC-RISKY-002",
            name="risky_division computes the quotient",
            target="risky_division",
            description="risky_division(10, 2) returns 5.",
            params=[10, 2],
            expected=5,
            tags=["risky_division"],
        ),
        TestCase(
            id="TC-SUM-001",
            name="sum adds every element of the array",
            target="sum_array",
            description="sum_array over {1, 2, 3, 4} returns 10.",
            params=["&values", 4],
            setup=[
                "int values[4];",
                "values[0] = 1;",
                "values[1] = 2;",
                "values[2] = 3;",
                "values[3] = 4;",
            ],
            expected=10,
            requirement_ids=["REQ-005"],
            tags=["sum", "iteration"],
        ),
        TestCase(
            id="TC-LOOPS-001",
            name="loops terminates for a bounded limit",
            target="loops",
            description="loops(5) returns a deterministic value.",
            params=[5],
            tags=["loops"],
        ),
        TestCase(
            id="TC-COMPARE-001",
            name="compare_ints returns the absolute difference",
            target="compare_ints",
            description="compare_ints(3, 9) returns 6.",
            params=[3, 9],
            expected=6,
            tags=["compare"],
        ),
        TestCase(
            id="TC-LIST-001",
            name="build_list creates the requested number of nodes",
            target="build_list",
            description="build_list(3) returns a list of three nodes.",
            params=[3],
            requirement_ids=[],
            tags=["list"],
        ),
        TestCase(
            id="TC-LIST-002",
            name="list_length counts the nodes",
            target="list_length",
            description="A freshly built list has the expected length.",
            params=["$list"],
            setup=["Node *list = build_list(3);"],
            expected=3,
            tags=["list"],
        ),
    ],
)

SUITES = [SUITE]
